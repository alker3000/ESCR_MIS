<?php

namespace App\Services;

use App\Models\Enrollment;
use App\Models\Invoice;
use App\Models\Payment;
use App\Models\PromissoryNote;
use App\Models\SystemSetting;
use App\Models\User;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

class PaymentService
{
    /**
     * Process a Student Payment (Instant GCash Sandbox, Manual GCash QR/Reference, or Walk-In Cash at Cashier).
     */
    public function processGCashPayment(
        Invoice $invoice,
        User $student,
        array $data,
        ?UploadedFile $proofFile = null
    ): Payment {
        return DB::transaction(function () use ($invoice, $student, $data, $proofFile) {
            $mode = $data['payment_mode'] ?? 'sandbox_instant';
            $isInstant = ($mode === 'sandbox_instant');
            $isCash = ($mode === 'walk_in_cash');
            $paymentMethod = $isCash ? 'cash' : 'gcash';

            $proofPath = null;
            if ($proofFile instanceof UploadedFile) {
                $ext = $proofFile->getClientOriginalExtension() ?: 'png';
                $proofPath = $proofFile->storeAs(
                    'documents/payments/' . $student->id,
                    Str::uuid()->toString() . '.' . $ext,
                    'local'
                );
            }

            if ($isCash) {
                $refNumber = !empty($data['cash_reference_number'])
                    ? trim($data['cash_reference_number'])
                    : 'CSH-2026-' . strtoupper(Str::random(3)) . rand(100, 999);
            } else {
                $refNumber = !empty($data['gcash_reference_number'])
                    ? trim($data['gcash_reference_number'])
                    : '90' . rand(10000000000, 99999999999);
            }

            $remarks = match ($mode) {
                'sandbox_instant' => 'Auto-verified via GCash Sandbox Express Checkout.',
                'walk_in_cash' => 'Walk-in Cash Payment Slip generated by student. Awaiting over-the-counter cash payment at School Cashier.',
                default => 'Manual GCash QR / Reference submitted by student for Cashier verification.',
            };

            $payment = Payment::create([
                'receipt_number' => 'OR-2026-' . strtoupper(Str::random(3)) . rand(1000, 9999),
                'invoice_id' => $invoice->id,
                'user_id' => $student->id,
                'payment_method' => $paymentMethod,
                'payment_mode' => $mode,
                'gcash_reference_number' => $refNumber,
                'gcash_sender_name' => $data['gcash_sender_name'] ?? $student->name,
                'gcash_sender_number' => $data['gcash_sender_number'] ?? ($student->contact_number ?: '09171234567'),
                'amount' => $invoice->balance() > 0 ? $invoice->balance() : $invoice->amount,
                'proof_file_path' => $proofPath,
                'status' => $isInstant ? 'verified' : 'pending',
                'verified_by' => null,
                'verified_at' => $isInstant ? now() : null,
                'cashier_remarks' => $remarks,
            ]);

            if ($isInstant) {
                $this->applyVerifiedPayment($payment, null);
            } else {
                $invoice->update(['status' => 'pending_verification']);

                AuditService::log(
                    'PAYMENT_SUBMITTED',
                    $isCash
                        ? "Student {$student->name} generated Walk-In Cash Slip #{$payment->gcash_reference_number} for {$invoice->invoice_number}."
                        : "Student {$student->name} submitted Manual GCash Ref #{$payment->gcash_reference_number} for {$invoice->invoice_number}.",
                    'Payment',
                    $payment->id,
                    null,
                    ['amount' => $payment->amount, 'method' => $paymentMethod, 'ref' => $payment->gcash_reference_number],
                    $student
                );
            }

            return $payment;
        });
    }

    /**
     * Cashier manually verifies a pending GCash or Walk-in Cash payment, or system auto-verifies a sandbox payment.
     */
    public function verifyPayment(Payment $payment, User $cashier, ?string $remarks = null): Payment
    {
        return DB::transaction(function () use ($payment, $cashier, $remarks) {
            $defaultRemarks = $payment->payment_method === 'cash'
                ? 'Cash payment received over-the-counter and verified by School Cashier.'
                : 'GCash reference number verified by School Cashier.';

            $payment->update([
                'status' => 'verified',
                'verified_by' => $cashier->id,
                'verified_at' => now(),
                'cashier_remarks' => $remarks ?? $defaultRemarks,
            ]);

            $this->applyVerifiedPayment($payment, $cashier);

            return $payment;
        });
    }

    /**
     * Cashier rejects an invalid GCash reference number submission.
     */
    public function rejectPayment(Payment $payment, User $cashier, string $remarks): Payment
    {
        return DB::transaction(function () use ($payment, $cashier, $remarks) {
            $payment->update([
                'status' => 'rejected',
                'verified_by' => $cashier->id,
                'verified_at' => now(),
                'cashier_remarks' => $remarks,
            ]);

            $invoice = $payment->invoice;
            if ($invoice && $invoice->status === 'pending_verification') {
                $invoice->update([
                    'status' => $invoice->due_date && $invoice->due_date->isPast() ? 'overdue' : 'unpaid',
                ]);
            }

            AuditService::log(
                'PAYMENT_REJECTED',
                "Cashier {$cashier->name} rejected GCash payment {$payment->receipt_number}: {$remarks}",
                'Payment',
                $payment->id,
                ['status' => 'pending'],
                ['status' => 'rejected', 'remarks' => $remarks],
                $cashier
            );

            NotificationService::send(
                $payment->user,
                'payment_verified',
                "GCash Payment Rejected ({$invoice?->invoice_number})",
                "Dear {$payment->user->name},\n\nYour submitted GCash payment (Ref #{$payment->gcash_reference_number}) could not be verified by the Cashier.\nReason: {$remarks}\n\nPlease review and resubmit valid payment details.\n\nEast Systems Colleges of Rizal"
            );

            return $payment;
        });
    }

    /**
     * Apply a verified payment to its invoice and trigger downstream enrollment, exam clearance, or tela workflows.
     */
    protected function applyVerifiedPayment(Payment $payment, ?User $verifier = null): void
    {
        $invoice = $payment->invoice;
        $student = $payment->user;

        $invoice->update([
            'amount_paid' => $invoice->amount,
            'status' => 'paid',
            'paid_at' => now(),
        ]);

        // 1. If initial Downpayment or Full Tuition is paid -> Officially Enroll the Student!
        if (in_array($invoice->invoice_type, ['full_tuition', 'downpayment'], true)) {
            $enrollment = $invoice->enrollment ?? $student->enrollment;
            if ($enrollment && $enrollment->status !== 'enrolled') {
                $enrollment->update([
                    'status' => 'enrolled',
                    'enrolled_at' => now(),
                ]);
            }

            if (!$student->student_number) {
                $student->update([
                    'student_number' => 'ESCR-2026-' . str_pad((string) $student->id, 4, '0', STR_PAD_LEFT),
                ]);
            }

            NotificationService::send(
                $student,
                'enrollment_status',
                "Officially Enrolled for SY 2026-2027 ({$student->student_number})",
                "Congratulations {$student->name}!\n\nYour GCash payment of PHP " . number_format((float) $payment->amount, 2) . " (Receipt #{$payment->receipt_number}) has been verified. You are now OFFICIALLY ENROLLED at East Systems Colleges of Rizal for SY 2026-2027.\n\nStudent Number: {$student->student_number}\n\nThank you!"
            );
        }

        // 2. If Uniform Fabric (Tela) order invoice is paid -> Route to Cashier Dashboard for fulfillment!
        if ($invoice->invoice_type === 'tela_order' && $invoice->telaOrder) {
            $invoice->telaOrder->update([
                'status' => 'paid_processing',
            ]);
        }

        // 3. Recompute Student Exam Clearance / Restriction Status
        $enrollment = $invoice->enrollment ?? $student->enrollment;
        if ($enrollment) {
            $this->refreshExamClearanceStatus($enrollment);
        }

        // 4. Send Official Receipt notification
        $channelLabel = $payment->payment_method === 'cash' ? 'Cash (Over-the-Counter)' : 'GCash';
        NotificationService::send(
            $student,
            'payment_verified',
            "Payment Verified - Official Receipt {$payment->receipt_number}",
            "Dear {$student->name},\n\nWe have verified your {$channelLabel} payment of PHP " . number_format((float) $payment->amount, 2) . " for {$invoice->title} ({$invoice->invoice_number}).\n\nOfficial Receipt No.: {$payment->receipt_number}\nReference No.: {$payment->gcash_reference_number}\n\nYou may download your PDF Official Receipt anytime from the Billing section of your portal.\n\nEast Systems Colleges of Rizal"
        );

        AuditService::log(
            'PAYMENT_VERIFIED',
            ($verifier ? "Cashier {$verifier->name}" : "GCash Sandbox Gateway") . " verified payment {$payment->receipt_number} (PHP " . number_format((float) $payment->amount, 2) . ") for {$invoice->invoice_number}.",
            'Payment',
            $payment->id,
            ['invoice_status' => 'unpaid'],
            ['invoice_status' => 'paid', 'receipt_number' => $payment->receipt_number],
            $verifier ?? $student
        );
    }

    /**
     * Request an Incomplete Completion (Remedial) Fee invoice for a student.
     */
    public function createCompletionFeeInvoice(User $student, string $subjectCode, string $remarks = ''): Invoice
    {
        $enrollment = $student->enrollment;
        $feeAmount = (float) SystemSetting::getValue('completion_fee', 500.00);

        $invoice = Invoice::create([
            'invoice_number' => 'CMP-2026-' . strtoupper(Str::random(3)) . rand(100, 999),
            'user_id' => $student->id,
            'enrollment_id' => $enrollment?->id,
            'invoice_type' => 'completion_fee',
            'exam_period' => null,
            'title' => "Incomplete Completion (Remedial) Fee - {$subjectCode}",
            'description' => trim("Completion/remedial processing fee for subject {$subjectCode}. {$remarks}"),
            'amount' => $feeAmount,
            'amount_paid' => 0,
            'due_date' => now()->addDays(7)->toDateString(),
            'status' => 'unpaid',
        ]);

        AuditService::log(
            'COMPLETION_FEE_CREATED',
            "Created Incomplete Completion Fee invoice {$invoice->invoice_number} for {$student->name} ({$subjectCode}).",
            'Invoice',
            $invoice->id,
            null,
            ['subject' => $subjectCode, 'amount' => $feeAmount],
            $student
        );

        return $invoice;
    }

    /**
     * Evaluate whether a student's account has any overdue installments or unpaid special exam fees.
     */
    public function refreshExamClearanceStatus(Enrollment $enrollment): void
    {
        $invoices = Invoice::where('user_id', $enrollment->user_id)->get();

        $overdueInstallments = $invoices->filter(function (Invoice $inv) {
            return $inv->isInstallment() && ($inv->status === 'overdue' || ($inv->status === 'unpaid' && $inv->due_date && $inv->due_date->isPast()));
        });

        // Mark any past-due unpaid installments as 'overdue'
        foreach ($overdueInstallments as $ov) {
            if ($ov->status === 'unpaid') {
                $ov->update(['status' => 'overdue']);
            }
        }

        // Check if there are any unpaid Special Exam Fee invoices
        $unpaidSpecialFees = $invoices->filter(function (Invoice $inv) {
            return $inv->invoice_type === 'special_exam_fee' && $inv->status !== 'paid';
        });

        if ($overdueInstallments->isNotEmpty()) {
            $firstOverdue = $overdueInstallments->first();
            $enrollment->update([
                'exam_restricted' => true,
                'exam_restriction_reason' => "Overdue {$firstOverdue->title} (PHP " . number_format((float) $firstOverdue->amount, 2) . "). Promissory Note submission is closed for late installments — please pay the overdue balance via GCash or Walk-In Cash to lift your exam restriction.",
            ]);
            return;
        }

        if ($unpaidSpecialFees->isNotEmpty()) {
            $firstSpecial = $unpaidSpecialFees->first();
            $enrollment->update([
                'exam_restricted' => true,
                'exam_restriction_reason' => "Promissory Note approved, but {$firstSpecial->title} (PHP " . number_format((float) $firstSpecial->amount, 2) . ") must be paid via GCash before you are cleared to take the special exam.",
            ]);
            return;
        }

        $enrollment->update([
            'exam_restricted' => false,
            'exam_restriction_reason' => null,
        ]);
    }
}
